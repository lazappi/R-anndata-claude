suppressMessages(library(rhdf5))
f <- tempfile(fileext = ".h5")
h5createFile(f)
m <- matrix(1:12, 3, 4)
h5write(m, f, "m")
h <- H5Fopen(f)
d <- H5Dopen(h, "m")
sp <- H5Dget_space(d)
print(H5Sget_simple_extent_dims(sp)$size)
H5Sselect_index(sp, list(c(2, 3), c(1, 4)))
print(H5Dread(d, h5spaceFile = sp, h5spaceMem = H5Screate_simple(c(2, 2))))
print(m[c(2, 3), c(1, 4)])
print(h5read(f, "m", index = list(c(2, 3), c(1, 4))))
